using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using RecallSmith.Lambda.Worker.Content;
using RecallSmith.Lambda.Worker.Repositories;
using RecallSmith.Lambda.Worker.S3;
using RecallSmith.Lambda.Worker.Services;

namespace RecallSmith.Lambda.IntegrationTests;

// Pure fake S3/repository, but the real previous-deck parser, mapper, diff and artifact generator.
public class TeachingDeltaContractTests
{
  private static string SamplePath
  {
    get
    {
      for (var d = new DirectoryInfo(AppContext.BaseDirectory); d is not null; d = d.Parent)
      {
        var path = Path.Combine(d.FullName, "contracts/content-v1/samples/delta-v2.json");
        if (File.Exists(path)) return path;
      }
      throw new FileNotFoundException("delta-v2.json");
    }
  }

  private sealed class Uploader(string previous) : IS3DeckUploader
  {
    public readonly Dictionary<string, string> Uploaded = new();
    public Task<S3UploadResult> UploadAsync(string key, DeckExportData data) => throw new NotSupportedException();
    public Task<string> DownloadJsonAsync(string key) => Task.FromResult(previous);
    public Task<S3UploadResult> UploadJsonAsync(string key, string json, string cacheControl)
    {
      Uploaded.Add(key, json);
      return Task.FromResult(new S3UploadResult { Bytes = Encoding.UTF8.GetByteCount(json), Sha256 = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(json))).ToLowerInvariant() });
    }
  }

  private sealed class Repository : IContentArtifactsRepository
  {
    public int PatchCount;
    public Task<PreviousBuildInfo?> GetLatestSuccessBuildAsync(long id) => Task.FromResult<PreviousBuildInfo?>(new PreviousBuildInfo { BuildId = "old-build-1", S3Key = "content/decks/csharp/builds/old-build-1/deck.json" });
    public Task UpdateContentMetadataAsync(string job, string sha, long bytes, string? package) => Task.CompletedTask;
    public Task InsertBuildPatchAsync(string slug, string from, string to, string path, string key, string sha, long bytes)
    {
      PatchCount++;
      return Task.CompletedTask;
    }
  }

  [Theory]
  [InlineData("unchanged")]
  [InlineData("reordered")]
  [InlineData("tags-only")]
  [InlineData("zh-only")]
  [InlineData("remove-teaching")]
  [InlineData("remove-tags")]
  [InlineData("add-teaching")]
  [InlineData("add-tags")]
  public async Task GeneratedPatch_RoundtripsSameRevisionTeachingAndTags(string name)
  {
    var fixture = JsonNode.Parse(File.ReadAllText(SamplePath))!;
    var test = fixture["cases"]!.AsArray().Single(c => c!["name"]!.GetValue<string>() == name)!;
    var previous = fixture["previous"]!.DeepClone();
    if (test["previousCard"] is { } old) previous["cards"]![1] = old.DeepClone();
    var next = previous.DeepClone();
    next["version"] = test["patch"]!["toVersion"]!.DeepClone();
    next["cards"]![1] = test["nextCard"]!.DeepClone();
    var nextDeck = next.Deserialize<DeckExportData>(ContentJson.Options)!;
    var uploader = new Uploader(previous.ToJsonString());
    var repository = new Repository();
    var version = nextDeck.Version;
    var job = new JobInfo { JobId = $"teaching-delta-{name}", BuildId = version, DeckId = 1, DeckSlug = "csharp", S3Key = $"content/decks/csharp/builds/{version}/deck.json", Status = "PROCESSING" };
    var full = ContentJson.Serialize(nextDeck);
    await new ContentArtifactsGenerator(uploader, repository).GenerateAsync(job, nextDeck, new S3UploadResult { Bytes = Encoding.UTF8.GetByteCount(full) });
    var patchText = uploader.Uploaded[$"content/decks/csharp/patches/old-build-1-{version}.json"];
    Assert.Equal(1, repository.PatchCount);
    Assert.True(Encoding.UTF8.GetByteCount(patchText) < Encoding.UTF8.GetByteCount(full));
    var actual = JsonNode.Parse(patchText)!;
    actual["generatedAtMs"] = 0; // Only the wall-clock field differs from the shared mobile fixture.
    Assert.True(JsonNode.DeepEquals(test["patch"], actual), $"{name}: {actual}");
    Assert.Equal(7, nextDeck.Cards[1].Revision);
    // Optional evidence export lets the mobile public installer consume these exact generated bytes.
    if (Environment.GetEnvironmentVariable("N5_DELTA_OUTPUT_DIR") is { Length: > 0 } output)
    {
      Directory.CreateDirectory(output);
      File.WriteAllText(Path.Combine(output, $"{name}.previous.json"), previous.ToJsonString());
      File.WriteAllText(Path.Combine(output, $"{name}.patch.json"), patchText);
      File.WriteAllText(Path.Combine(output, $"{name}.next.json"), full);
    }
  }
}
